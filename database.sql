CREATE TABLE IF NOT EXISTS municipalities (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL, code VARCHAR(20) NULL, wilaya_name VARCHAR(120) NOT NULL, INDEX idx_wilaya (wilaya_name), UNIQUE KEY uq_municipality (name,wilaya_name)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
